import type { ClusterStatusResponse } from '../types';

export function generateMarkdownReport(data: ClusterStatusResponse): string {
  const timestamp = new Date().toISOString();
  const placedPods = data.pods.filter((p) => p.nodeName && p.phase !== 'Pending');
  const pendingPods = data.pods.filter((p) => !p.nodeName || p.phase === 'Pending');

  return `# Cloud Computing Lab Evaluation 2 — Cluster Scheduling Report
**Problem 07: Pod Scheduling Using Taints and Tolerations**
**Generated At:** ${timestamp}
**Cluster Context:** \`${data.context}\`
**Namespace:** \`${data.namespace}\`
**Cluster Connected:** ${data.clusterConnected ? 'Yes' : 'No'}
**GPU Node Reserved:** ${data.gpuReserved ? 'YES (hardware=gpu:NoSchedule)' : 'NO'}

---

## 1. Executive Summary
- **Total Nodes:** ${data.nodes.length}
- **Placed Pods:** ${placedPods.length}
- **Pending Pods in Queue:** ${pendingPods.length}

---

## 2. Cluster Nodes & Taint Policies
${data.nodes
  .map(
    (n) => `### Node: \`${n.name}\` (${n.role})
- **Labels:** ${Object.entries(n.labels || {}).map(([k, v]) => `\`${k}=${v}\``).join(', ') || 'none'}
- **Active Taints:** ${n.taints && n.taints.length > 0
      ? n.taints.map((t) => `\`${t.key}${t.value ? `=${t.value}` : ''}:${t.effect}\``).join(', ')
      : 'None (open to all workloads)'}
- **Scheduled Pods (${placedPods.filter((p) => p.nodeName === n.name).length}):**
${placedPods
  .filter((p) => p.nodeName === n.name)
  .map((p) => `  - \`${p.name}\` (app: \`${p.app}\`, phase: \`${p.phase}\`)`)
  .join('\n') || '  - None'}
`
  )
  .join('\n')}

---

## 3. Pending Queue (Unscheduled Workloads)
${pendingPods.length === 0
  ? '*No workloads pending. All pods successfully scheduled.*'
  : pendingPods
      .map(
        (p) => `- **\`${p.name}\`** (app: \`${p.app}\`, phase: \`${p.phase}\`)
  - Tolerations: ${JSON.stringify(p.tolerations || [])}
  - nodeSelector: ${JSON.stringify(p.nodeSelector || {})}`
      )
      .join('\n')}

---

## 4. Recent Kubernetes Scheduling Events
| Timestamp | Type | Reason | Object | Message |
| --- | --- | --- | --- | --- |
${data.events
  .slice(0, 20)
  .map(
    (e) => `| ${e.lastTimestamp || 'N/A'} | ${e.type} | **${e.reason}** | \`${e.object}\` | ${e.message.replace(/\|/g, '\\|')} |`
  )
  .join('\n')}

---

## 5. Command Execution Audit Trail
${(data.commandLogs || [])
  .slice(0, 15)
  .map(
    (l) => `### [${l.timestamp}] ${l.label} (Exit Code: ${l.exitCode})
\`\`\`bash
$ ${l.command}
${l.output || '(no output)'}
\`\`\`
`
  )
  .join('\n')}

---
*Report generated by GPU Node Scheduling Studio — Cloud Computing Lab Evaluation 2.*
`;
}

export function downloadReport(filename: string, content: string, contentType: string) {
  const blob = new Blob([content], { type: contentType });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

export function exportMarkdownReport(data: ClusterStatusResponse) {
  const md = generateMarkdownReport(data);
  const dateStr = new Date().toISOString().replace(/[:.]/g, '-');
  downloadReport(`gpu-scheduling-report-${dateStr}.md`, md, 'text/markdown;charset=utf-8');
}

export function exportJsonReport(data: ClusterStatusResponse) {
  const json = JSON.stringify(data, null, 2);
  const dateStr = new Date().toISOString().replace(/[:.]/g, '-');
  downloadReport(`cluster-state-${dateStr}.json`, json, 'application/json;charset=utf-8');
}
